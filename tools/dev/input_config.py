#!/usr/bin/env python3
"""The typed configs of the C++ and Python APIs, generated from the key catalog.

    python tools/dev/input_config.py           write include/mallard/config.h and tools/mallard/config.py
    python tools/dev/input_config.py --check   exit 1 if either is out of date

Each table of the input (docs/input-keys/, the keys setup reads) becomes a class whose setters, one per key, are
typed by the catalog (bool, integer, number, string; a quantity with its unit for a key with a physical dimension)
and documented by the key's row in docs/input.md (else by the catalog's default and accepted values). The classes
only collect keys and values: Case::set (mallard.Case.set) writes them into the case's TOML, which setup then reads
and checks as a file's. A table is an array of tables when the catalog types it as an array, docs/input.md heads it
`[[...]]`, or an input of the catalog writes it as one; a table whose keys are all species names (X, Y) is a map.
tools/dev/precheck.sh runs --check, so the generated files cannot drift from the catalog.
"""
import argparse
import keyword
import re
import sys
import textwrap
import tomllib
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import input_catalog  # noqa: E402

ROOT = input_catalog.ROOT
HEADER = ROOT / "include" / "mallard" / "config.h"
MODULE = ROOT / "tools" / "mallard" / "config.py"
GENERATED = "Generated by tools/dev/input_config.py from docs/input-keys/ and docs/input.md: do not edit."
CPP_KEYWORDS = {"and", "auto", "bool", "break", "case", "catch", "char", "class", "const", "continue", "default",
                "delete", "do", "double", "else", "enum", "explicit", "export", "extern", "false", "float", "for",
                "friend", "goto", "if", "inline", "int", "long", "mutable", "namespace", "new", "not", "operator",
                "or", "private", "protected", "public", "register", "return", "short", "signed", "sizeof", "static",
                "struct", "switch", "template", "this", "throw", "true", "try", "typedef", "typename", "union",
                "unsigned", "using", "virtual", "void", "volatile", "while", "xor", "path", "entries", "put"}
PY_RESERVED = set(keyword.kwlist) | {"path", "entries"}


class Node:
    def __init__(self, path):
        self.path = path            # catalog path: "numerics.face_reconstruction", "regions.<name>"
        self.entry = None           # the catalog's entry, if the path is a key of it
        self.children = {}          # name: Node
        self.array = False          # an array of tables
        self.map = False            # keys are names (species): set as name -> value
        self.parent = None

    @property
    def name(self):
        return self.path.rsplit(".", 1)[-1]

    @property
    def table(self):
        return bool(self.children) and not self.map


def tree(catalog, arrays):
    root = Node("")
    for key in sorted(catalog):
        node = root
        parts = key.split(".")
        for i, part in enumerate(parts):
            if part not in node.children:
                node.children[part] = Node(".".join(parts[:i + 1]))
                node.children[part].parent = node
            node = node.children[part]
        node.entry = catalog[key]

    def mark(node):
        for child in node.children.values():
            mark(child)
        if node.children:
            node.array = node.path in arrays or (node.entry or {}).get("type") == "array"
            node.map = all(not c.children and re.fullmatch(r"[A-Z][A-Z0-9]*", c.name) for c in node.children.values())
    mark(root)
    return root


def walk(value, parts):
    """Whether the input value at parts (descending into every element of arrays) is an array of tables."""
    if not parts:
        return isinstance(value, list) and any(isinstance(v, dict) for v in value)
    if isinstance(value, list):
        return any(walk(v, parts) for v in value)
    if isinstance(value, dict) and parts[0] in value:
        return walk(value[parts[0]], parts[1:])
    return False


def array_paths(catalog):
    """The paths of the catalog's tables that are arrays of tables."""
    out = set()
    for line in (ROOT / "docs" / "input.md").read_text().splitlines():
        m = re.match(r"^#{2,4} `\[\[([\w.]+)\]\]`", line)
        if m:
            out.add(m.group(1))
    tables = {k.rsplit(".", 1)[0] for k in catalog if "." in k}
    inputs = {}
    for table in sorted(tables):
        for source in sorted({s for k, e in catalog.items() if k.startswith(table + ".") for s in e["set_in"]}):
            if source not in inputs:
                try:
                    inputs[source] = tomllib.loads((ROOT / source).read_text())
                except (OSError, tomllib.TOMLDecodeError):
                    inputs[source] = {}
            if walk(inputs[source], table.split(".")):
                out.add(table)
                break
    return out


def plain(text):
    """docs/input.md's text without links' targets and markdown emphasis."""
    text = re.sub(r"\s*\|\s*$", "", text).replace(" | ", "; ")
    text = re.sub(r"\[([^\]]+)\]\([^)]*\)", r"\1", text)
    return re.sub(r"\*\*([^*]+)\*\*", r"\1", text).strip()


def describe(node, descriptions):
    """The documentation of a key: its row of docs/input.md, then what the catalog says."""
    e = node.entry or {}
    out = []
    if node.path in descriptions:
        text = descriptions[node.path]
        out.append(text if text.endswith(".") else text + ".")
    facts = []
    if e.get("dimension"):
        unit = f", a number in {e['unit']}" if e.get("unit") else ", a number in SI units"
        facts.append(f"{e['dimension']}{unit} or a quantity with its unit")
    if e.get("values"):
        facts.append("one of " + ", ".join(e["values"]))
    if e.get("required"):
        facts.append("required")
    if node.path not in descriptions and "default" in e:
        default = f"default {e['default']}"
        for dim, value in sorted(e.get("defaults_by_dim", {}).items()):
            default += f" ({dim}D: {value})"
        facts.append(default)
    if e.get("dims") and len(e["dims"]) == 1:
        facts.append(f"{e['dims'][0]}D")
    if facts:
        out.append(facts[0][0].upper() + facts[0][1:] + "".join("; " + f for f in facts[1:]) + ".")
    return " ".join(out) or "A key of the input."


def camel(path):
    return "".join(p[:1].upper() + p[1:] for part in path.replace("<name>", "").split(".") for p in part.split("_") if p)


def classes(root):
    """Every table node with its class name, children before parents, and whether it is set alone (its path)."""
    out = []

    def visit(node):
        for child in node.children.values():
            if child.table:
                visit(child)
        if node.path and node.table and set(node.children) != {"<name>"}:
            out.append(node)
    for child in root.children.values():
        visit(child)
    names = {}
    for node in out:
        node.cls = camel(node.path)
        if node.cls in names:
            raise SystemExit(f"input_config.py: {node.path} and {names[node.cls]} both make class {node.cls}")
        names[node.cls] = node.path
    out.sort(key=lambda n: (-n.path.count("."), n.path))
    return out


def standalone(node):
    """How a table's class is placed: at its path (fixed), by index (an element of a top-level array), by name
    (a named table), or only by its parent's setter (nested: in an array of tables or a named table)."""
    parts = node.path.split(".")
    if len(parts) == 1 and node.array:
        return "index"
    if len(parts) == 2 and parts[1] == "<name>":
        return "name"
    up = node
    while up.path:
        if up.array or up.name == "<name>":
            return "nested"
        up = up.parent
    return "fixed"


def wrap(text, width, prefix):
    return textwrap.wrap(text, width - len(prefix), break_long_words=False, break_on_hyphens=False) or [""]


# ---------------------------------------------------------------------------------------------------- C++


def cpp_name(name):
    return name + "_" if name in CPP_KEYWORDS else name


def cpp_comment(text, indent):
    lines = wrap(text.replace("*/", "* /"), 116, indent + " * ")
    return [indent + "/** @brief " + lines[0]] + [indent + " *        " + line for line in lines[1:]] + [indent + " */"]


def cpp_setters(node, cls, descriptions):
    out = []
    for child in node.children.values():
        if child.name == "<name>":
            continue
        name = cpp_name(child.name)
        doc = cpp_comment(describe(child, descriptions), "        ")
        key = f'"{child.name}"'
        if child.table and child.array:
            body = (f"for (std::size_t i = 0; i < items.size(); i++) put({key} \"[\" + std::to_string(i) + \"]\", "
                    "items[i]); return *this;")
            out += doc + [f"        {cls} & {name}(const std::vector<{child.cls}> & items) {{ {body} }}"]
        elif child.table:
            out += doc + [f"        {cls} & {name}(const {child.cls} & t) {{ put({key}, t); return *this; }}",
                          f"        /** @brief {child.name} as a value (a region's name, an inline table). */",
                          f"        {cls} & {name}(const Value & v) {{ put({key}, v); return *this; }}"]
        elif child.map:
            out += doc + [f"        {cls} & {name}(std::string_view species, const Value & v) {{ "
                          f"put(std::string({key} \".\") + std::string(species), v); return *this; }}"]
        else:
            e = child.entry or {}
            t = e.get("type")
            param = {"bool": "bool v", "integer": "std::int64_t v", "string": "std::string_view v",
                     "number": "Quantity v" if e.get("dimension") else "double v"}.get(t, "const Value & v")
            if t == "array" and e.get("dimension"):
                out += doc + [f"        {cls} & {name}(const std::vector<Quantity> & v) {{ "
                              f"put({key}, Value(std::vector<Value>(v.begin(), v.end()))); return *this; }}"]
                continue
            out += doc + [f"        {cls} & {name}({param}) {{ put({key}, v); return *this; }}"]
    return out


def header(root, descriptions):
    out = ["/**", " * @file config.h",
           " * @brief Typed configs: a class per table of the input, a setter per key, for Case::set.",
           " *", " * " + GENERATED,
           " * Guide: docs/guide/cpp_api.md#typed-configs.", " */", "",
           "#ifndef MALLARD_CONFIG_H", "#define MALLARD_CONFIG_H", "", "#include <cstddef>", "#include <cstdint>",
           "#include <string>", "#include <string_view>", "#include <vector>", "", '#include "mallard/mallard.h"', "",
           "namespace mallard::config {", ""]
    for node in classes(root):
        cls = node.cls
        place = standalone(node)
        kind = "array of tables" if node.array else "table"
        shown = node.path.replace("<name>", "NAME")
        out += cpp_comment(f"[{'[' if node.array else ''}{shown}{']' if node.array else ''}]: "
                           f"the keys of this {kind} " + {
                               "fixed": "the case sets.",
                               "index": "the case sets in its element index (index = its length appends one).",
                               "name": "the case sets in the named table.",
                               "nested": "its parent's setter takes."}[place], "")
        out.append(f"class {cls} : public Table {{")
        out.append("    public:")
        if place == "fixed":
            out.append(f'        {cls}() : Table("{node.path}") {{}}')
        elif place == "index":
            out.append(f'        explicit {cls}(std::size_t element) : Table("{node.path}[" + std::to_string(element) + "]") {{}}')
        elif place == "name":
            top = node.path.split(".")[0]
            out.append(f'        explicit {cls}(std::string_view table_name) : Table("{top}." + std::string(table_name)) {{}}')
        else:
            out.append(f'        {cls}() : Table("") {{}}')
        out += cpp_setters(node, cls, descriptions)
        out += ["};", ""]
    out += ["} // namespace mallard::config", "", "#endif // MALLARD_CONFIG_H", ""]
    return "\n".join(out)


# ---------------------------------------------------------------------------------------------------- Python


def py_name(name):
    return name + "_" if name in PY_RESERVED else name


def py_kind(child):
    if child.table:
        return ("array" if child.array else "table"), child.cls
    if child.map:
        return "map", None
    e = child.entry or {}
    return ("quantity" if e.get("dimension") else "value"), None


def py_hint(child):
    if child.table:
        return f"list[{child.cls}] | None" if child.array else f"{child.cls} | dict | Inline | str | None"
    if child.map:
        return "dict | None"
    e = child.entry or {}
    t = e.get("type")
    if e.get("dimension"):
        return "list | None" if t == "array" else "float | str | tuple | None"
    if t == "string" and e.get("values"):
        return "Literal[" + ", ".join(repr(v) for v in e["values"]) + "] | str | None"
    return {"bool": "bool | None", "integer": "int | None", "number": "float | None", "string": "str | None",
            "array": "list | None"}.get(t, "object")


def module(root, descriptions):
    out = ['"""Typed configs: a class per table of the input, a keyword per key, for mallard.Case.set.', "",
           "    case = case.set(config.Run(dt=\"1 us\", n_steps=100))", "",
           GENERATED, "Guide: docs/guide/python.md#typed-configs.", '"""', "from __future__ import annotations", "",
           "from typing import Literal", "", "from ._config import Inline, Table", ""]
    names = []
    for node in classes(root):
        cls = node.cls
        place = standalone(node)
        names.append(cls)
        shown = node.path.replace("<name>", "NAME")
        title = f"[{'[' if node.array else ''}{shown}{']' if node.array else ''}]"
        lead = {"fixed": "", "index": "index, ", "name": "name, ", "nested": ""}[place]
        path = {"fixed": repr(node.path), "index": f'f"{node.path}[{{index}}]"',
                "name": f'f"{node.path.split(".")[0]}.{{name}}"', "nested": '""'}[place]
        out += ["", f"class {cls}(Table):"]
        how = {"fixed": "the case sets.", "index": "the case sets in its element index (its length appends one).",
               "name": "the case sets in the named table.", "nested": "its parent's keyword takes."}[place]
        out.append(f'    """{title}: the keys of this {"array of tables" if node.array else "table"} {how}"""')
        keys = [c for c in node.children.values() if c.name != "<name>"]
        out.append("    _keys = {")
        for child in keys:
            kind, ref = py_kind(child)
            out.append(f"        {py_name(child.name)!r}: ({child.name!r}, {kind!r}, {ref!r}),")
        out.append("    }")
        out.append("")
        params = ", ".join(f"{py_name(c.name)}: {py_hint(c)} = None" for c in keys)
        out.append(f"    def __init__(self, {lead}*, {params}):" if params else f"    def __init__(self, {lead}):")
        doc = ['        r"""']
        for child in keys:
            lines = wrap(f"{py_name(child.name)}: {describe(child, descriptions)}", 116, " " * 12)
            doc += ["        " + lines[0]] + ["            " + line for line in lines[1:]]
        out += doc + ['        """'] if len(doc) > 1 else []
        args = ", ".join(f"{py_name(c.name)!r}: {py_name(c.name)}" for c in keys)
        out.append(f"        super().__init__({path}, {{{args}}})")
    out += ["", "", "__all__ = [" + ", ".join(repr(n) for n in ["Inline", "Table"] + sorted(names)) + "]", ""]
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    catalog = input_catalog.load(input_catalog.CATALOG)
    descriptions = {}
    for paths, _, text in input_catalog.documented_rows():
        for path in paths:
            descriptions.setdefault(path, plain(text))
    root = tree(catalog, array_paths(catalog))
    files = {HEADER: header(root, descriptions), MODULE: module(root, descriptions)}
    stale = [f for f, text in files.items() if not f.exists() or f.read_text() != text]
    if args.check:
        if stale:
            sys.exit(", ".join(str(f.relative_to(ROOT)) for f in stale) + " out of date with docs/input-keys/ "
                     "and docs/input.md: run python tools/dev/input_config.py")
        print(f"typed configs: up to date ({len(catalog)} keys)")
        return
    for f in stale:
        f.write_text(files[f])
    print(f"wrote {', '.join(str(f.relative_to(ROOT)) for f in stale) or 'nothing (up to date)'}")


if __name__ == "__main__":
    main()
