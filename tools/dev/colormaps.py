#!/usr/bin/env python3
"""Writes src/io/colormaps.inc, the colormaps of `mallard post render`: 256 sRGB colors each.

    python3 tools/dev/colormaps.py            # needs matplotlib
    python3 tools/dev/colormaps.py --check    # fails if the file is stale

viridis, magma, inferno, plasma and cividis are matplotlib's (CC0, by Stefan van der Walt,
Nathaniel Smith and Jamie Nuñez); coolwarm is Moreland's diverging map, computed here from its
definition (K. Moreland, "Diverging Color Maps for Scientific Visualization", ISVC 2009); gray
runs from black to white.
"""
import argparse
import sys
from pathlib import Path

import numpy as np

OUT = Path(__file__).resolve().parents[2] / "src" / "io" / "colormaps.inc"
MATPLOTLIB = ["viridis", "magma", "inferno", "plasma", "cividis"]

# sRGB <-> CIELAB (D65), as in Moreland's paper
WHITE = np.array([0.95047, 1.0, 1.08883])
M = np.array([[0.4124, 0.3576, 0.1805], [0.2126, 0.7152, 0.0722], [0.0193, 0.1192, 0.9505]])


def to_linear(c):
    return np.where(c > 0.04045, ((c + 0.055) / 1.055) ** 2.4, c / 12.92)


def to_srgb(c):
    return np.where(c > 0.0031308, 1.055 * np.maximum(c, 0) ** (1 / 2.4) - 0.055, 12.92 * c)


def lab(rgb):
    xyz = M @ to_linear(np.asarray(rgb, float)) / WHITE
    f = np.where(xyz > 0.008856, np.cbrt(xyz), 7.787 * xyz + 16 / 116)
    return np.array([116 * f[1] - 16, 500 * (f[0] - f[1]), 200 * (f[1] - f[2])])


def rgb(lab_):
    fy = (lab_[0] + 16) / 116
    f = np.array([fy + lab_[1] / 500, fy, fy - lab_[2] / 200])
    xyz = np.where(f > 0.206893, f ** 3, (f - 16 / 116) / 7.787) * WHITE
    return np.clip(to_srgb(np.linalg.solve(M, xyz)), 0, 1)


def msh(lab_):
    m = np.linalg.norm(lab_)
    return np.array([m, np.arccos(lab_[0] / m), np.arctan2(lab_[2], lab_[1])])


def lab_of(msh_):
    m, s, h = msh_
    return np.array([m * np.cos(s), m * np.sin(s) * np.cos(h), m * np.sin(s) * np.sin(h)])


def adjust_hue(sat, unsat_m):
    m, s, h = sat
    if m >= unsat_m - 0.1:
        return h
    spin = s * np.sqrt(unsat_m ** 2 - m ** 2) / (m * np.sin(s))
    return h + spin if h > -np.pi / 3 else h - spin


def diverging(a, b, x):
    p, q = msh(lab(a)), msh(lab(b))
    if p[1] > 0.05 and q[1] > 0.05 and abs(p[2] - q[2]) > np.pi / 3:
        mid = max(p[0], q[0], 88.0)
        if x < 0.5:
            q, x = np.array([mid, 0.0, 0.0]), 2 * x
        else:
            p, x = np.array([mid, 0.0, 0.0]), 2 * x - 1
    if p[1] < 0.05 < q[1]:
        p[2] = adjust_hue(q, p[0])
    elif q[1] < 0.05 < p[1]:
        q[2] = adjust_hue(p, q[0])
    return rgb(lab_of((1 - x) * p + x * q))


def tables():
    import matplotlib

    out = {name: matplotlib.colormaps[name](np.linspace(0, 1, 256))[:, :3] for name in MATPLOTLIB}
    cool, warm = np.array([59, 76, 192]) / 255, np.array([180, 4, 38]) / 255
    out["coolwarm"] = np.array([diverging(cool, warm, x) for x in np.linspace(0, 1, 256)])
    out["gray"] = np.repeat(np.linspace(0, 1, 256)[:, None], 3, axis=1)
    return out


def text():
    lines = ["// Generated by tools/dev/colormaps.py; do not edit. 256 sRGB colors per colormap.", ""]
    for name, t in tables().items():
        b = np.rint(np.clip(t, 0, 1) * 255).astype(int).ravel()
        lines.append(f'{{"{name}", {{')
        for i in range(0, len(b), 24):
            lines.append("    " + ", ".join(str(v) for v in b[i:i + 24]) + ",")
        lines.append("}},")
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    new = text()
    if args.check:
        if OUT.read_text() != new:
            sys.exit(f"{OUT} is stale: run python3 tools/dev/colormaps.py")
        return
    OUT.write_text(new)


if __name__ == "__main__":
    main()
